export function getRuntimeReversePhraseMap(): RuntimePhraseMap {
  const reverse: RuntimePhraseMap = {};
  [ru, uz].forEach((phrases) => {
    Object.entries(phrases).forEach(([source, translated]) => {
      reverse[translated] = source;
    });
  });
  return reverse;
}
